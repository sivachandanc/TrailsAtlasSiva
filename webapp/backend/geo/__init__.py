"""Where a 5-digit ZIP code is, and straight-line distances in miles.

ZIP points are the internal points of the 2024 US Census ZCTAs (zip_centroids.csv, ~33.8k rows,
regenerated by build_zip_centroids.py). Loaded once, on first use.
"""

import csv
import math
from functools import cache
from pathlib import Path

CENTROIDS = Path(__file__).with_name("zip_centroids.csv")
EARTH_RADIUS_MILES = 3958.8

Point = tuple[float, float]  # (lat, lon)


@cache
def centroids() -> dict[str, Point]:
    with CENTROIDS.open(newline="") as f:
        return {r["zip"]: (float(r["lat"]), float(r["lon"])) for r in csv.DictReader(f)}


def normalize_zip(value) -> str | None:
    """The 5-digit ZIP from '02139', '2139' (leading zero lost), '02139-4307' or 2139; None if it isn't one."""
    if value is None:
        return None
    text = str(value).strip().split("-")[0]
    return text.zfill(5) if text.isdigit() and 3 <= len(text) <= 5 else None


def zip_point(value) -> Point | None:
    z = normalize_zip(value)
    return centroids().get(z) if z else None


def haversine_miles(a: Point, b: Point) -> float:
    lat1, lon1, lat2, lon2 = map(math.radians, (*a, *b))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 2 * EARTH_RADIUS_MILES * math.asin(math.sqrt(h))


