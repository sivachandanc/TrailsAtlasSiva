NAME_BY_LOWER = {name.lower(): name for name in STATE_NAMES.values()}


def state_name(value) -> str | None:
    """'OH', 'oh' or 'Ohio' -> 'Ohio'; anything else is returned trimmed, or None if blank."""
    text = str(value or "").strip()
    if not text:
        return None
    return STATE_NAMES.get(text.upper()) or NAME_BY_LOWER.get(text.lower()) or text
